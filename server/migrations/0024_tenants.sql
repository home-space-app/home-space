-- The default fills in existing rows only. Dropped right after, so every new row has to name its
-- tenant and an insert that forgets it fails instead of landing in tenant 1. Tenants are deleted
-- through their users by a background job, never by a cascade.
ALTER TABLE users ADD COLUMN tenant_id INTEGER NOT NULL DEFAULT 1
    REFERENCES tenants (id) ON DELETE RESTRICT;
ALTER TABLE users ALTER COLUMN tenant_id DROP DEFAULT;
-- Two tenants may both have a user called admin.
ALTER TABLE users DROP CONSTRAINT users_username_key;
ALTER TABLE users ADD CONSTRAINT users_tenant_username UNIQUE (tenant_id, username);
-- The target of the composite foreign keys that keep a row's tenant equal to its user's.
ALTER TABLE users ADD CONSTRAINT users_tenant_id_key UNIQUE (tenant_id, id);

-- Two tenants may use the same identity provider, and the same person may be a user in both.
ALTER TABLE user_identities ADD COLUMN tenant_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE user_identities ALTER COLUMN tenant_id DROP DEFAULT;
ALTER TABLE user_identities DROP CONSTRAINT user_identities_pkey;
ALTER TABLE user_identities ADD PRIMARY KEY (tenant_id, issuer, subject);
-- An identity's tenant is always its user's.
ALTER TABLE user_identities DROP CONSTRAINT user_identities_user_id_fkey;
ALTER TABLE user_identities ADD CONSTRAINT user_identities_user_fkey FOREIGN KEY (tenant_id, user_id)
    REFERENCES users (tenant_id, id) ON DELETE CASCADE;

-- Failed sign-ins are counted per tenant and username. The count of an address over all
-- usernames (username '') is shared by every tenant, so that an attacker gets no free guesses
-- per tenant; its rows have tenant 0, which no tenant has, hence no foreign key.
ALTER TABLE login_attempts ADD COLUMN tenant_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE login_attempts ALTER COLUMN tenant_id DROP DEFAULT;
UPDATE login_attempts SET tenant_id = 0 WHERE username = '';
ALTER TABLE login_attempts DROP CONSTRAINT login_attempts_pkey;
ALTER TABLE login_attempts ADD PRIMARY KEY (tenant_id, username, source);

-- A sign-in sent to the provider comes back only to the tenant that sent it.
ALTER TABLE oidc_pending ADD COLUMN tenant_id INTEGER NOT NULL DEFAULT 1
    REFERENCES tenants (id) ON DELETE CASCADE;
ALTER TABLE oidc_pending ALTER COLUMN tenant_id DROP DEFAULT;
