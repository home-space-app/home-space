-- One installation serves several tenants, each on its own domains with its own users. Every
-- existing row belongs to tenant 1, so an install upgraded from before keeps working as it was.
-- See docs/todo/multi-tenancy.md.

CREATE TABLE tenants (
    id          INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name        TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- A disabled tenant answers 503 on every route and its users can't sign in.
    disabled_at TIMESTAMPTZ,
    -- Like users.delete_at: a background job deletes the tenant's users, then the tenant.
    delete_at   TIMESTAMPTZ
);

-- The hosts a tenant answers on. Exactly one is primary: it makes the public URL (OIDC
-- callback, links in e-mails later). The others are aliases that keep old links and installed
-- clients working after a move.
CREATE TABLE tenant_domains (
    -- The host, lower-cased, with :port when it is not the default one.
    domain     TEXT PRIMARY KEY CHECK (domain = lower(domain) AND length(domain) BETWEEN 1 AND 260),
    tenant_id  INTEGER NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
    is_primary BOOLEAN NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX tenant_domains_primary ON tenant_domains (tenant_id) WHERE is_primary;
CREATE INDEX tenant_domains_tenant_idx ON tenant_domains (tenant_id);

